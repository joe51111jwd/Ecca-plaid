/**
 * npx tsx scripts/make-fixtures.ts [--check]
 *
 * Writes the SYNTHETIC document fixtures (src/engine/documents/synthetic-catalog.ts) to
 * tests/fixtures/synthetic/ together with manifest.json, which states for every file the expected
 * classification, field values and review reasons. Output is deterministic; the files are committed as test
 * data and demo material.
 *
 *   --check   regenerate in memory and exit non-zero if any committed file or the manifest differs.
 *
 * Every person, number and agency in these files is fictional. No real family document is ever used.
 */
import { existsSync, mkdirSync, readdirSync, readFileSync, unlinkSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { parseArgs } from "node:util";
import { FIXTURE_HOUSEHOLD, FIXTURE_REFERENCE_DATE, SYNTHETIC_FIXTURES } from "@/engine/documents/synthetic-catalog";

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const OUT = join(ROOT, "tests", "fixtures", "synthetic");

function buildManifest() {
  return {
    note: "SYNTHETIC SAMPLE — NOT A REAL DOCUMENT. Generated by scripts/make-fixtures.ts from src/engine/documents/synthetic-catalog.ts; do not edit by hand.",
    referenceDate: FIXTURE_REFERENCE_DATE,
    household: FIXTURE_HOUSEHOLD,
    policy: "default (every unverified-layout auto-accept flag off)",
    fixtures: SYNTHETIC_FIXTURES.map((f) => ({
      id: f.id,
      file: f.file,
      ...(f.reuses ? { reuses: f.reuses } : {}),
      description: f.description,
      proves: f.proves,
      contentType: f.contentType,
      declaredKind: f.declaredKind,
      expected: f.expected,
    })),
  };
}

async function main(): Promise<void> {
  const { values } = parseArgs({ options: { check: { type: "boolean", default: false } } });
  const files = new Map<string, Uint8Array>();
  for (const f of SYNTHETIC_FIXTURES) {
    if (!f.build) continue;
    if (files.has(f.file)) throw new Error(`Two fixtures build ${f.file}`);
    files.set(f.file, await f.build());
  }
  for (const f of SYNTHETIC_FIXTURES) {
    if (!files.has(f.file)) throw new Error(`${f.id} reads ${f.file}, which no fixture builds`);
  }
  files.set("manifest.json", new TextEncoder().encode(`${JSON.stringify(buildManifest(), null, 2)}\n`));

  if (values.check) {
    const stale = [...files].filter(([name, bytes]) => {
      const path = join(OUT, name);
      return !existsSync(path) || Buffer.compare(readFileSync(path), Buffer.from(bytes)) !== 0;
    });
    if (stale.length > 0) {
      console.error(`Out of date: ${stale.map(([n]) => n).join(", ")}. Run: npx tsx scripts/make-fixtures.ts`);
      process.exit(1);
    }
    console.log(`All ${files.size} synthetic fixture files are up to date.`);
    return;
  }

  mkdirSync(OUT, { recursive: true });
  // Remove files of fixtures that no longer exist, so the directory mirrors the catalog.
  for (const name of readdirSync(OUT)) {
    if (/^SYNTHETIC_/.test(name) && !files.has(name)) unlinkSync(join(OUT, name));
  }
  for (const [name, bytes] of files) writeFileSync(join(OUT, name), bytes);
  console.log(`Wrote ${files.size} files to ${OUT}`);
}

main().catch((e: unknown) => {
  console.error(e);
  process.exit(1);
});

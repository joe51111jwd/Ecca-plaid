const CRC_TABLE = (() => {
  const t = new Uint32Array(256);
  for (let n = 0; n < 256; n++) {
    let c = n;
    for (let k = 0; k < 8; k++) c = c & 1 ? 0xedb88320 ^ (c >>> 1) : c >>> 1;
    t[n] = c >>> 0;
  }
  return t;
})();

function crc32(bytes: Uint8Array): number {
  let c = 0xffffffff;
  for (const b of bytes) c = CRC_TABLE[(c ^ b) & 0xff] ^ (c >>> 8);
  return (c ^ 0xffffffff) >>> 0;
}

function chunk(type: string, data: Uint8Array): Uint8Array {
  const out = new Uint8Array(12 + data.length);
  const view = new DataView(out.buffer);
  view.setUint32(0, data.length);
  for (let i = 0; i < 4; i++) out[4 + i] = type.charCodeAt(i);
  out.set(data, 8);
  view.setUint32(8 + data.length, crc32(out.subarray(4, 8 + data.length)));
  return out;
}

export interface RasterLine {
  text: string;
  /** Pixel size of one font dot. */
  scale?: number;
  /** 0 = black … 255 = white. */
  shade?: number;
}

/** Renders the lines (upper-cased; unknown characters become spaces) to a PNG. */
export function renderTextPng(lines: readonly RasterLine[], opts: { width?: number; margin?: number } = {}): Uint8Array {
  const margin = opts.margin ?? 24;
  const heights = lines.map((l) => 9 * (l.scale ?? 2));
  const width = opts.width ?? Math.max(200, margin * 2 + Math.max(...lines.map((l) => l.text.length * 6 * (l.scale ?? 2))));
  const height = margin * 2 + heights.reduce((a, b) => a + b, 0);
  const pixels = new Uint8Array(width * height).fill(255);
  let top = margin;
  lines.forEach((line, li) => {
    const s = line.scale ?? 2;
    const shade = line.shade ?? 0;
    [...line.text.toUpperCase()].forEach((ch, ci) => {
      const glyph = GLYPHS[ch] ?? GLYPHS[" "];
      for (let row = 0; row < 7; row++) {
        for (let col = 0; col < 5; col++) {
          if (!(glyph[row] & (0x10 >> col))) continue;
          for (let dy = 0; dy < s; dy++) {
            for (let dx = 0; dx < s; dx++) {
              const x = margin + (ci * 6 + col) * s + dx;
              const y = top + row * s + dy;
              if (x < width && y < height) pixels[y * width + x] = shade;
            }
          }
        }
      }
    });
    top += heights[li];
  });
  // PNG rows: filter byte 0 + grayscale samples.
  const raw = new Uint8Array(height * (width + 1));
  for (let y = 0; y < height; y++) raw.set(pixels.subarray(y * width, (y + 1) * width), y * (width + 1) + 1);
  const ihdr = new Uint8Array(13);
  const v = new DataView(ihdr.buffer);
  v.setUint32(0, width);
  v.setUint32(4, height);
  ihdr.set([8, 0, 0, 0, 0], 8);
  const parts = [
    new Uint8Array([0x89, 0x50, 0x4e, 0x47, 0x0d, 0x0a, 0x1a, 0x0a]),
    chunk("IHDR", ihdr),
    chunk("IDAT", zlibSync(raw, { level: 9 })),
    chunk("IEND", new Uint8Array(0)),
  ];
  const out = new Uint8Array(parts.reduce((a, p) => a + p.length, 0));
  let o = 0;
  for (const p of parts) {
    out.set(p, o);
    o += p.length;
  }
  return out;
}
